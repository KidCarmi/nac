"""Apply the product-generated EOS config plus isolated service-port wiring.

Run inside EVE with SWITCH_ACTION=inventory|configure|status. The RADIUS secret
is read from the existing root-only disposable lab file and never printed.
"""

import os
from pathlib import Path
import re
import secrets
import select
import socket
import time


PORT = 32799
SECRET = Path("/root/nac-pki/radius.secret").read_text().strip()
EAPI_PATH = Path('/root/nac-pki/eapi-observer.secret')


def read(sock, seconds):
    output = bytearray()
    deadline = time.monotonic() + seconds
    while time.monotonic() < deadline:
        if select.select([sock], [], [], 0.1)[0]:
            part = sock.recv(65536)
            if not part:
                break
            output.extend(part)
    clean = re.sub(r"\x1b\[[0-9;?]*[A-Za-z]", "", output.decode(errors="replace"))
    clean = clean.replace(SECRET, "[REDACTED]")
    if EAPI_PATH.exists():
        clean = clean.replace(EAPI_PATH.read_text().strip(), '[REDACTED]')
    clean = re.sub(r"(radius-server host \S+ key 7) \S+", r"\1 [REDACTED]", clean)
    return clean.replace("\r", "")


with socket.create_connection(("127.0.0.1", PORT), timeout=5) as sock:
    sock.sendall(b"\r\n")
    greeting = read(sock, 4)
    if "login:" in greeting:
        sock.sendall(b"admin\r\n")
        greeting += read(sock, 3)
    if not re.search(r'nac-veos-rc1[>#]', greeting):
        raise RuntimeError('isolated EOS console did not reach an authenticated prompt')
    def cmd(value, seconds=1.2):
        sock.sendall(value.encode() + b"\r\n")
        result = read(sock, seconds)
        if "% Invalid" in result or "% Error" in result:
            raise RuntimeError(f"EOS rejected {value.replace(SECRET, '[REDACTED]')}: {result[-500:]}")
        return result

    action = os.environ.get("SWITCH_ACTION", "")
    if action == "inventory":
        cmd("terminal length 0")
        print("VERSION", cmd("show version | include Software image version", 2).strip())
        cmd("enable")
        print("INTERFACES", cmd("show running-config | section interface Ethernet", 2)[-2500:])
        print("RADIUS", cmd("show running-config | include radius-server", 1).strip())
    elif action == "configure":
        cmd("enable")
        cmd("configure terminal")
        # Generated by the product's Switches screen on pilot-rc1.
        for value in ("hostname nac-veos-rc1", "vlan 10", "name corp", "vlan 20", "name quarantine",
                      f"radius-server host 10.70.99.2 key {SECRET}",
                      "aaa authentication dot1x default group radius", "dot1x system-auth-control",
                      "dot1x dynamic-authorization", "interface Ethernet1",
                      "switchport access vlan 10", "dot1x pae authenticator", "dot1x port-control auto"):
            cmd(value)
        # EVE-only service and routed control-port wiring from the proven lab.
        for value in ("interface Ethernet2", "switchport access vlan 10", "interface Ethernet3",
                      "switchport access vlan 20", "interface Ethernet4", "no switchport",
                      "ip address 10.70.99.1/24", "end"):
            cmd(value)
        print("SAVE", cmd("write memory", 3)[-1000:])
        print("CONFIGURED_PRODUCT_AND_LAB_PORTS")
        print("RADIUS", cmd("show running-config | include radius-server", 1).strip())
        print("DOT1X", cmd("show running-config | include dot1x", 1).strip())
        print("CONTROL", cmd("show ip interface brief | include Ethernet4", 1).strip())
    elif action == "status":
        cmd("terminal length 0")
        cmd("enable")
        print("PORT_CONFIG", cmd("show running-config | section interface Ethernet", 2)[:2500])
        print("VLANS", cmd("show vlan brief", 2)[-1000:])
        print("HOSTS", cmd("show dot1x hosts", 2)[-1800:])
    elif action == "clear_session":
        cmd("enable")
        print("CLEAR", cmd("clear dot1x host all", 2)[-500:])
        print("HOSTS", cmd("show dot1x hosts", 2)[-800:])
    elif action == "storage":
        cmd("enable")
        try:
            print("STARTUP", cmd("show startup-config", 2)[-2400:])
        except RuntimeError as exc:
            print("STARTUP_ERROR", str(exc)[-500:])
        print("FLASH", cmd("dir flash:", 2)[-1200:])
    elif action == "cancel_ztp":
        cmd("enable")
        print("ZTP_CANCEL", cmd("zerotouch cancel", 3)[-1000:])
    elif action == 'enable_observation':
        if not EAPI_PATH.exists():
            EAPI_PATH.write_text(secrets.token_urlsafe(30))
            EAPI_PATH.chmod(0o600)
        observer = EAPI_PATH.read_text().strip()
        cmd('enable')
        cmd('configure terminal')
        cmd(f'username nac-observer role network-operator secret {observer}')
        cmd('management api http-commands')
        cmd('no shutdown')
        cmd('exit')
        cmd('aaa accounting dot1x default start-stop group radius')
        cmd('end')
        print('SAVE', cmd('write memory', 3)[-700:])
        print('OBSERVER_CONFIGURED secret root-only in EVE')
        print('API', cmd('show management api http-commands', 2)[-1100:])
        print('ACCOUNTING', cmd('show running-config | include aaa accounting dot1x', 1)[-400:])
    elif action == 'observation_status':
        cmd('enable')
        print('API', cmd('show management api http-commands', 2)[-1100:])
        print('ACCOUNTING', cmd('show running-config | include aaa accounting dot1x', 1)[-400:])
        print('DOT1X', cmd('show dot1x hosts', 2)[-1000:])
        print('PORT', cmd('show interfaces Ethernet1 status', 2)[-700:])
    elif action == 'tls_inventory':
        cmd('enable')
        print('API', cmd('show management api http-commands', 2)[-1200:])
        print('SSL_PROFILE', cmd('show management security ssl profile', 2)[-1800:])
        print('VERSION', cmd('show version | include Software image version', 2)[-400:])
    elif action in {'persistence_status', 'save_rc10'}:
        cmd('terminal length 0')
        cmd('enable')
        running = cmd('show running-config', 3)
        if action == 'save_rc10':
            required = ('radius-server host 10.70.99.4 ',
                        'ssl profile nac-eapi',
                        'protocol https ssl profile nac-eapi',
                        'aaa accounting dot1x default start-stop group radius')
            missing = [line for line in required if line not in running]
            if missing:
                raise RuntimeError('refusing to save incomplete rc10 running config: '+repr(missing))
            print('SAVE', cmd('write memory', 4)[-500:])
        startup = cmd('show startup-config', 3)
        def selected(config):
            return [line.strip() for line in config.splitlines()
                    if any(term in line for term in
                           ('radius-server host', 'ssl profile nac-eapi',
                            'protocol https ssl profile nac-eapi',
                            'aaa accounting dot1x default start-stop group radius'))]
        print('RUNNING_SELECTED', selected(running))
        print('STARTUP_SELECTED', selected(startup))
        print('STARTUP_MATCHES_RC10',
              all(line in startup for line in
                  ('radius-server host 10.70.99.4 ', 'ssl profile nac-eapi',
                   'protocol https ssl profile nac-eapi')))
        print('SESSION', cmd('show dot1x hosts', 2)[-900:])
    elif action in {'clean_control','restore_control','rc10_control','rc10_after_restart','rc4_control'}:
        old, new = ({'clean_control': ('10.70.99.2','10.70.99.3'),
                     'restore_control': ('10.70.99.3','10.70.99.2'),
                     'rc10_control': ('10.70.99.3','10.70.99.4'),
                     'rc10_after_restart': ('10.70.99.2','10.70.99.4'),
                     'rc4_control': ('10.70.99.4','10.70.99.2')}[action])
        cmd('enable')
        cmd('configure terminal')
        cmd(f'no radius-server host {old}')
        cmd(f'radius-server host {new} key {SECRET}')
        cmd('end')
        radius = cmd('show running-config | include radius-server host',2)
        print('RADIUS_HOSTS', sorted(set(re.findall(r'radius-server host ([0-9.]+)',radius))))
        print('CONFIG_UNSAVED_RESTORABLE', action)
    elif action in {'disable_eapi_diagnostic','restore_eapi_diagnostic'}:
        cmd('enable')
        if 'nac-veos-rc1' not in cmd('show hostname', 1):
            raise RuntimeError('unexpected isolated switch hostname')
        print('BEFORE',cmd('show management api http-commands', 2)[-600:])
        cmd('configure terminal')
        cmd('management api http-commands')
        cmd('shutdown' if action=='disable_eapi_diagnostic' else 'no shutdown')
        cmd('end')
        print('AFTER',cmd('show management api http-commands', 2)[-600:])
        print('DOT1X',cmd('show dot1x hosts', 2)[-600:])
    elif action == 'port_bounce':
        cmd('enable')
        cmd('configure terminal')
        cmd('interface Ethernet1')
        print('SHUTDOWN', cmd('shutdown', 2)[-300:])
        time.sleep(2)
        print('NO_SHUTDOWN', cmd('no shutdown', 2)[-300:])
        cmd('end')
        print('PORT', cmd('show interfaces Ethernet1 status', 2)[-700:])
    elif action == 'diagnose_forwarding':
        cmd('terminal length 0')
        cmd('enable')
        print('CLOCK', cmd('show clock', 1)[-300:])
        print('HOSTS', cmd('show dot1x hosts', 2)[-900:])
        print('PORT', cmd('show interfaces Ethernet1 status', 1)[-700:])
        print('MAC', cmd('show mac address-table interface Ethernet1', 2)[-1000:])
        print('COUNTERS', cmd('show interfaces Ethernet1 counters', 2)[-1300:])
    elif action == 'reauth_help':
        cmd('enable')
        for value in ('dot1x re-authenticate Ethernet ?',
                      'dot1x re-authenticate Ethernet 1 ?', 'clear dot1x host ?'):
            print('HELP', value, cmd(value, 2)[-1400:])
    elif action == 'reauth_local':
        cmd('enable')
        before = cmd('show dot1x hosts', 2)
        if '0050.0000.0200' not in before or 'SUCCESS' not in before or '10' not in before:
            raise RuntimeError('expected active Windows session on VLAN 10')
        print('CLOCK_BEFORE', cmd('show clock', 1)[-250:])
        print('SESSION_BEFORE', before[-650:])
        print('REAUTH', cmd('dot1x re-authenticate Ethernet 1', 2)[-500:])
        print('CLOCK_AFTER', cmd('show clock', 1)[-250:])
    elif action == 'config_checkpoint_help':
        cmd('enable')
        print('COPY_HELP', cmd('copy running-config ?', 2)[-1400:])
        print('REPLACE_HELP', cmd('configure replace ?', 2)[-1400:])
    elif action == 'checkpoint_pre_fresh':
        cmd('enable')
        running = cmd('show running-config', 3)
        if 'radius-server host 10.70.99.4 ' not in running or 'ssl profile nac-eapi' not in running:
            raise RuntimeError('current rc10 switch configuration is not the expected baseline')
        filename = 'nac-rc10-before-fresh.cfg'
        if filename in cmd('dir flash:', 2):
            raise RuntimeError('checkpoint filename already exists')
        print('COPY', cmd('copy running-config flash:' + filename, 4)[-500:])
        if filename not in cmd('dir flash:', 2):
            raise RuntimeError('EOS did not create checkpoint')
        print('CHECKPOINT_VERIFIED', 'flash:' + filename)
    elif action in {'fresh_ui_target', 'restore_rc10_target'}:
        old, new = (('10.70.99.4', '10.70.99.5') if action == 'fresh_ui_target'
                    else ('10.70.99.5', '10.70.99.4'))
        cmd('enable')
        running = cmd('show running-config', 3)
        if f'radius-server host {old} ' not in running or f'radius-server host {new} ' in running:
            raise RuntimeError('unexpected RADIUS target before ' + action)
        if 'ssl profile nac-eapi' not in running or 'aaa accounting dot1x default start-stop group radius' not in running:
            raise RuntimeError('trusted observation or accounting baseline missing')
        cmd('configure terminal')
        cmd(f'no radius-server host {old}')
        cmd(f'radius-server host {new} key {SECRET}')
        cmd('end')
        hosts = cmd('show running-config | include radius-server host', 2)
        if f'radius-server host {new} ' not in hosts or f'radius-server host {old} ' in hosts:
            raise RuntimeError('RADIUS target did not switch')
        print('SAVE', cmd('write memory', 4)[-500:])
        print('RADIUS_TARGET', new)
        print('PRESERVED_TLS_ACCOUNTING', True)
    elif action == 'fresh_ui_status':
        cmd('terminal length 0')
        cmd('enable')
        running = cmd('show running-config', 3)
        startup = cmd('show startup-config', 3)
        selected = ('radius-server host 10.70.99.5 ',
                    'dot1x system-auth-control', 'dot1x dynamic-authorization',
                    'aaa accounting dot1x default start-stop group radius',
                    'ssl profile nac-eapi', 'protocol https ssl profile nac-eapi')
        print('RUNNING_REQUIRED', {line: line in running for line in selected})
        print('STARTUP_REQUIRED', {line: line in startup for line in selected})
        print('HOSTS', cmd('show dot1x hosts', 2)[-900:])
        print('EAPI', cmd('show management api http-commands', 2)[-900:])
    else:
        raise SystemExit("set SWITCH_ACTION=inventory|configure|status|clear_session|storage|cancel_ztp|enable_observation|observation_status|port_bounce|diagnose_forwarding")

